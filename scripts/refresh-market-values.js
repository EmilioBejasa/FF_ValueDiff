#!/usr/bin/env node
// Writes data/market-values.js: KeepTradeCut, DynastyProcess and Dynasty
// Superflex trade values (via Dynasty Daddy, see lib/dynasty-daddy.js), for
// the trade calculator's "What other calculators say" panel.
//
// Usage: node scripts/refresh-market-values.js [--dry-run]
//
// None of these sites send a CORS header, so the page can't fetch them
// itself; the daily refresh-market-values Action runs this instead. The file
// is a plain script (it sets window.MARKET_VALUES) so the page also works
// opened straight from disk.

const fs = require("fs");
const path = require("path");
const { MARKETS, fetchMarket } = require("./lib/dynasty-daddy");

const OUT = path.join(__dirname, "..", "data", "market-values.js");
const DRY_RUN = process.argv.includes("--dry-run");

async function main() {
  const values = {};
  for (const m of MARKETS) {
    values[m.key] = await fetchMarket(m.market);
    const n = Object.keys(values[m.key]["1qb"]).length;
    console.log(`${m.label}${m.mode === "redraft" ? " (redraft)" : ""}: ${n} values`);
    if (n < 100) throw new Error(`Suspiciously few ${m.label} values — ${OUT} left as is.`);
  }

  const body = JSON.stringify(values);
  const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (prev.includes(body)) return console.log("Values unchanged — file left as is.");

  const today = new Date().toISOString().slice(0, 10);
  const source =
    `// Generated by scripts/refresh-market-values.js — don't edit by hand.\n` +
    `window.MARKET_VALUES = { updatedOn: ${JSON.stringify(today)}, values: ${body} };\n`;
  if (DRY_RUN) return console.log(`Dry run — ${OUT} not written (${source.length} bytes).`);
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, source);
  console.log(`Wrote ${OUT} (${source.length} bytes)`);
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
